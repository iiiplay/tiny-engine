"""掃資料夾自動產生素材表（manifest.js）——不用再手量切圖尺寸

用法：
    python tools/gen_manifest.py <資料夾> [--fw 16] [--rows 1] [--out game/manifest.gen.js]
                                        [--prefix assets/pack] [--json]
    python tools/gen_manifest.py assets/pack --fw 16 --out game/manifest.gen.js

它會做這些事：
  1) 遞迴找所有 .png
  2) 檔名像 `Foo_f0.png` / `Foo_f12.png`（連續編號）→ 合成一個「逐格動畫」陣列
  3) 其他檔案：寬度是 --fw 的整數倍而高度是 --rows 的整數倍 → 當成 sprite sheet
     · frames = 寬 / fw，fh = 高 / rows
     · foot 預設 = fh（腳底對齊整格），可用 --foot 覆寫
  4) 輸出：
     const SRC = {...}            // 給 frameOf / drawFrames / drawSprite 用
     const ANIM = { name: [..] }  // 逐格動畫（檔名有 _f0 的那種）
     const MANIFEST = {...}       // 給 loadAll()
     const SHEET_DEF = {...}      // 給 sheetOf(assetDef(...)) 的現成參數

輸出的檔案是「純資料」，可以直接 import（<script src>）或用 --json 印出來。
"""
import argparse
import json
import os
import re
import sys

IMG_EXT = ('.png',)


def scan(root):
    out = []
    for dirpath, _dirnames, filenames in os.walk(root):
        for fn in sorted(filenames):
            if fn.lower().endswith(IMG_EXT):
                out.append(os.path.join(dirpath, fn))
    return out


def keyname(rel):
    """檔名 → 變數名字（去掉路徑、副檔名、非英數）"""
    base = os.path.splitext(os.path.basename(rel))[0]
    base = re.sub(r'[^0-9A-Za-z]+', '_', base).strip('_')
    if not base:
        base = 'img'
    if base[0].isdigit():
        base = 'n' + base
    return base.lower()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('folder')
    ap.add_argument('--fw', type=int, default=16, help='一格幾 px（預設 16）')
    ap.add_argument('--rows', type=int, default=1, help='sheet 有幾列（預設 1）')
    ap.add_argument('--foot', type=int, default=None, help='腳底對齊用（預設 = 每格高度）')
    ap.add_argument('--prefix', default=None, help='輸出裡的路徑前綴（預設沿用資料夾路徑）')
    ap.add_argument('--out', default=None, help='輸出檔案（沒給就印到 stdout）')
    ap.add_argument('--json', action='store_true', help='印 JSON 而不是 JS')
    ap.add_argument('--quiet', action='store_true')
    args = ap.parse_args()

    folder = args.folder.rstrip('/\\')
    if not os.path.isdir(folder):
        print('找不到資料夾：' + folder, file=sys.stderr)
        return 2

    try:
        from PIL import Image
        has_pil = True
    except Exception:
        has_pil = False

    files = scan(folder)
    prefix = args.prefix if args.prefix is not None else folder.replace('\\', '/')

    anim_groups = {}     # 名稱 -> [(index, path)]
    singles = []
    for path in files:
        rel = path.replace('\\', '/')
        base = os.path.splitext(os.path.basename(rel))[0]
        m = re.match(r'^(.*)_f(\d+)$', base)
        if m:
            anim_groups.setdefault(m.group(1), []).append((int(m.group(2)), rel))
        else:
            singles.append(rel)

    src = {}
    anim = {}
    sheet = {}
    used = set()

    def uniq(name):
        n = name
        i = 2
        while n in used:
            n = '%s%d' % (name, i)
            i += 1
        used.add(n)
        return n

    def srckey(rel):
        return (prefix + '/' + os.path.relpath(rel, folder).replace('\\', '/')) if args.prefix is not None \
            else rel

    for group, items in sorted(anim_groups.items()):
        items.sort()
        name = uniq(keyname(group))
        paths = [srckey(rel) for _i, rel in items]
        anim[name] = paths
        for i, pth in enumerate(paths):
            src['%s_%d' % (name, i)] = pth

    for rel in singles:
        name = uniq(keyname(rel))
        path = srckey(rel)
        src[name] = path
        if has_pil:
            w, h = Image.open(os.path.join(folder, os.path.relpath(rel, folder))).size
        else:
            w, h = (0, 0)
        frames = 1
        fh = h
        if w and w % args.fw == 0 and w > args.fw:
            frames = w // args.fw
        if h and args.rows > 1 and h % args.rows == 0:
            fh = h // args.rows
        if frames > 1 or args.rows > 1:
            sheet[name] = {
                'src': path, 'frames': frames, 'fw': args.fw,
                'rows': args.rows, 'fh': fh,
                'foot': args.foot if args.foot is not None else fh,
                'w': w, 'h': h,
            }

    if args.json:
        out = json.dumps({'SRC': src, 'ANIM': anim, 'SHEET_DEF': sheet},
                         indent=2, ensure_ascii=False)
    else:
        lines = [
            '/* AUTO-GENERATED by tools/gen_manifest.py — 不要手改（改完重跑就好）',
            '   素材資料夾：%s' % folder,
            '   fw=%d rows=%d%s */' % (args.fw, args.rows,
                                       '' if args.foot is None else ' foot=%d' % args.foot),
            '',
            'const SRC = {',
        ]
        for k in sorted(src):
            lines.append("  %s: '%s'," % (k, src[k]))
        lines.append('};')
        lines.append('')
        if anim:
            lines.append('/* 逐格動畫（一格一張 PNG）：drawFrames(ANIM.xxx, t, fps, x, y) */')
            lines.append('const ANIM = {')
            for k in sorted(anim):
                lines.append('  %s: [' % k)
                for p in anim[k]:
                    lines.append("    '%s'," % p)
                lines.append('  ],')
            lines.append('};')
            lines.append('')
        if sheet:
            lines.append('/* sprite sheet 參數（給 sheetOf(assetDef(...)) 用） */')
            lines.append('const SHEET_DEF = {')
            for k in sorted(sheet):
                d = sheet[k]
                lines.append("  %s: { src: '%s', frames: %d, fw: %d, rows: %d, fh: %d, foot: %d },"
                             % (k, d['src'], d['frames'], d['fw'], d['rows'], d['fh'], d['foot']))
            lines.append('};')
            lines.append('')
        lines.append('/* 給 loadAll() 用 */')
        lines.append('const MANIFEST = {};')
        lines.append('for (const k in SRC) MANIFEST[SRC[k]] = { src: SRC[k] };')
        for k in sorted(sheet):
            lines.append("MANIFEST[SHEET_DEF.%s.src] = SHEET_DEF.%s;" % (k, k))
        lines.append('')
        out = '\n'.join(lines)

    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)) or '.', exist_ok=True)
        with open(args.out, 'w', encoding='utf-8') as f:
            f.write(out)
        if not args.quiet:
            print('寫入 %s（%d 張圖、%d 組動畫、%d 張 sheet）'
                  % (args.out, len(src), len(anim), len(sheet)))
    else:
        print(out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
